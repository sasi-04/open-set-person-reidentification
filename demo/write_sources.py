"""
Write demo/samples/SOURCES.md: where every sample picture comes from, under what licence, and how it was made.

In plain words: before pictures of real people are put in a pack that is passed around a company, the pack must say who took
them, what the licence is and what was done to them. This file is generated from the machine-readable record that
``prepare_faces.py`` writes (faces/SOURCES.json) plus the two street scenes' details, so the text cannot drift from the files.

    python demo/write_sources.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SAMPLES = HERE / "samples"

SCENES = [
    ("scene_A_street_amsterdam.jpg", "Fons Heijnsbroek", "CC0 1.0 (public-domain dedication)",
     "https://commons.wikimedia.org/wiki/File:2010.04_-_%27Photo_of_people_and_Spring_in_the_city%27,_walking_along_the_street_Prins_Hendrikkade,_near_Central_Station_Amsterdam_city;_Dutch_urban_photography_by_Fons_Heijnsbroek,_Netherlands,_geotagged_(27456703400).jpg"),
    ("scene_B_station_square.jpg", "Fons Heijnsbroek", "CC0 1.0 (public-domain dedication)",
     "https://commons.wikimedia.org/wiki/File:Man_is_walking_with_other_people_over_the_station_square_of_Central_Station_Amsterdam_city;_free_photo,_Fons_Heijnsbroek,_11-04-2022.tif"),
]


def main() -> int:
    faces = json.loads((SAMPLES / "faces" / "SOURCES.json").read_text(encoding="utf-8"))
    lines = [
        "# Sources of the demo pictures",
        "",
        "Every picture in `demo/samples/` is either **public domain / CC0** or derived from one. Nothing here is a photograph of a",
        "private person. The licence of each Commons file was **checked by the preparation scripts, which refuse anything that is not",
        "public domain or CC0.** (Generated by `demo/write_sources.py`.)",
        "",
        "## 1. Body-matching samples (street scenes) - heads are blurred",
        "",
        "The body model never uses faces, and a licence for a picture is not a licence to circulate recognisable strangers, so the **head of every",
        "detected person is blurred** (`prepare_scenes.py`). These pictures therefore show the BODY path: with no usable face the system falls back",
        "to clothing and build and (by policy) asks for review rather than a MATCH.",
        "",
        "| File | Author | Licence | Source |",
        "|---|---|---|---|",
    ]
    for name, author, licence, url in SCENES:
        lines.append(f"| `{name}` | {author} | {licence} | [Wikimedia Commons]({url}) |")
    lines += [
        "",
        "Derived files (made by `make_samples.py` with fixed recipes, using the server's own person detector; **not tuned to make the demo look good**):",
        "",
        "| File | How it was made |",
        "|---|---|",
        "| `person_A_reference_1.jpg`, `person_A_reference_2.jpg` | tight crop of the most confident person in scene A; the second is its mirror image |",
        "| `query_1_same_person.jpg` | the same person \"seen again\": a looser crop at 55 % size, 20 % darker |",
        "| `query_2_stranger.jpg` | a tight crop of the most confident person in scene B (a different person, in a different place) |",
        "| `query_3_blurry.jpg` | the same person in a loose box, half size, heavily out of focus (blur radius 6) - built to trip the sharpness check |",
        "| `clip_street.avi` | a 3-second clip: scene A, then the stranger's part of scene B, then scene A (slow camera push-in) |",
        "",
        "**Honest limit:** \"the same person seen again\" is derived from the *same* source photo, because no public multi-camera photo of one person is",
        "bundled. It shows how the system behaves; it is not a test of cross-camera accuracy (that needs Market-1501).",
        "",
        "## 2. Face-matching samples (`samples/faces/`)",
        "",
        "Official NASA photographs on Wikimedia Commons (works of the US government, **public domain**). Three people: **Eileen Collins** and **Mae Jemison**",
        "are *enrolled* (two photos each, `enroll/`); new photos of them in different clothes, settings and years are the `test/` photos that should be",
        "recognised; **Sally Ride** is never enrolled, so her photos should be **UNKNOWN**. They are used only to show that a face matcher recognises",
        "the same person across photographs - nothing is inferred about anyone. Photos are the 960-pixel versions Commons serves, saved unchanged except for re-encoding.",
        "",
        "| File | Role | Person | Date | Author | Licence | Commons page |",
        "|---|---|---|---|---|---|---|",
    ]
    for record in faces:
        author = record["author"] or "NASA (not stated on the page)"
        lines.append(f"| `{record['file']}` | {record['role']} | {record['person'].title()} | {record['date'] or '-'} | {author} | {record['licence']} | [page]({record['page']}) |")
    lines += [
        "",
        "## 3. What is deliberately NOT in the pack",
        "",
        "* **LFW** (the standard face benchmark used for the measurements in `docs/FACE_AND_BODY_MATCHING.md`): news photographs with their own copyrights.",
        "  Only the *numbers* are included (`docs/results/`); `scripts/evaluate_face_lfw.py` downloads the data on the machine that runs it.",
        "* **Market-1501**: research licence, supplied by the user.",
        "* **Photos of colleagues or volunteers**: bring your own with `demo/face_check.py`, with each person's consent.",
        "",
    ]
    (SAMPLES / "SOURCES.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", SAMPLES / "SOURCES.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
