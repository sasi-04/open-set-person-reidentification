"""Write docs/API_REFERENCE.md from the running code, so it cannot drift from the real endpoints."""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "backend"))

from app.main import create_app  # noqa: E402

EXAMPLES = """
## Examples (real requests against a running server on port 8000)

```powershell
# is the server alive, and are the models loaded?
curl.exe http://127.0.0.1:8000/api/health
curl.exe http://127.0.0.1:8000/api/readiness

# enroll an authorised, consenting person (use curl.exe, not the PowerShell alias "curl")
curl.exe -X POST http://127.0.0.1:8000/api/gallery/enroll -F reference_id=subject-017 -F consent_confirmed=true `
  -F images_are_crops=false -F "images=@C:\\authorised\\a.jpg" -F "images=@C:\\authorised\\b.jpg"

# who is in this photo? mode: crop (the picture IS one person) | box | all (every detected person)
curl.exe -X POST http://127.0.0.1:8000/api/reid/predict -F mode=all -F top_k=5 -F "image=@C:\\photos\\query.jpg"
```

A `predict` answer contains, per person: the box and detector confidence (never mixed up with identity confidence), the
**decision** (`accepted` | `unknown` | `review_required`), the best candidate with its **face score**, **body score** and the
threshold it was compared with, a plain-language **reason**, the policy version that decided, and per-stage `timings_ms`.
Errors always look like `{"error": {"code", "message", "request_id", "details"}}`.

Roles (only enforced when `REID_AUTH_REQUIRED=true`; then send `X-API-Key`): **viewer** (read, run queries, the example) ·
**operator** (+ manage the gallery) · **admin** (+ thresholds, evaluations, reset).
"""


def main() -> int:
    app = create_app(load_models=False)
    schema = app.openapi()
    rows: dict[str, list[str]] = {}
    for path, methods in sorted(schema["paths"].items()):
        for method, operation in methods.items():
            if method.lower() not in {"get", "post", "delete", "put", "patch"}:
                continue
            tag = (operation.get("tags") or ["other"])[0]
            body = ""
            content = (operation.get("requestBody") or {}).get("content", {})
            if content:
                body = "body: " + ", ".join(sorted(content))
            query = [p["name"] for p in operation.get("parameters", []) if p.get("in") == "query"]
            needs = "; ".join(x for x in (body, ("query: " + ", ".join(query)) if query else "") if x) or "-"
            responses = ", ".join(sorted(operation.get("responses", {})))
            summary = (operation.get("summary") or "").replace("|", "/")
            rows.setdefault(tag, []).append(f"| `{method.upper()}` | `{path}` | {summary} | {needs} | {responses} |")

    lines = [
        "# API reference",
        "",
        "*Generated by `scripts/build_api_reference.py` from the application's own OpenAPI description - do not edit by hand.*",
        f"Interactive version (same content, with a try-it button): **http://127.0.0.1:8000/api/docs**. {len(schema['paths'])} paths.",
        "",
    ]
    for tag, items in rows.items():
        lines += [f"## {tag}", "", "| Method | Path | What it does | Needs | Status codes |", "|---|---|---|---|---|", *items, ""]
    lines.append(EXAMPLES.strip("\n"))
    target = REPO_ROOT / "docs" / "API_REFERENCE.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {target.relative_to(REPO_ROOT)} ({sum(len(v) for v in rows.values())} operations)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
